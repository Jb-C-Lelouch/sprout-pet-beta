"""Native pixel garden props, each with a ground anchor at (24,44)."""
def draw_decor(kind):
    from pixel_art import Pixels
    p=Pixels(48,48)
    if kind=='nest':
        p.oval(3,36,42,10,'#596144')
        p.polygon([(5,38),(5,21),(24,6),(42,22),(42,40),(5,40)],'#68563c')
        p.polygon([(8,23),(24,11),(39,24),(39,39),(8,39)],'#b99b65')
        for y in (25,30,35):p.line(9,y,38,y,'#91764f')
        p.oval(16,22,17,21,'#4b4936');p.oval(17,34,15,8,'#d6bb7b')
        p.polygon([(2,22),(23,3),(46,23),(43,27),(24,11),(5,27)],'#486039')
        p.polygon([(4,22),(23,5),(43,23),(40,23),(24,12),(7,25)],'#81964f')
        for x,y in ((12,18),(20,11),(29,14),(36,20)):p.line(x,y,x+5,y-1,'#b6be71')
    elif kind=='lantern':
        p.oval(12,39,25,6,'#596144');p.rect(22,24,4,17,'#776348')
        p.polygon([(15,16),(32,16),(30,30),(17,30)],'#655b42')
        p.rect(18,18,11,10,'#e5bf6e');p.rect(20,19,4,7,'#fff0b0')
        p.line(24,17,24,29,'#8f784b');p.line(15,29,32,29,'#736042',2)
        p.polygon([(13,16),(23,8),(34,16)],'#6f7d59');p.line(15,15,30,15,'#b6bc85')
    else:
        p.polygon([(11,26),(36,26),(32,42),(16,42)],'#995f43')
        p.polygon([(14,28),(33,28),(29,39),(18,39)],'#cc9163')
        p.rect(10,24,27,5,'#d2a475');p.line(12,24,34,24,'#e5c494')
        for x,y in ((17,16),(28,13),(23,20)):
            p.line(23,25,x,y,'#536d38',2)
            p.oval(x-5,y-3,11,7,'#78944c');p.line(x-3,y,x+3,y-1,'#b5c67b')
    return p
